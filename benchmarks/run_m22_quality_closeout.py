def run_prediction(input_path: Path, prediction_path: Path, metadata_path: Path,
                   model: Path, work_dir: Path, run_id: str, spec: DatasetSpec,
                   arm: str, cpu_threads: int, timeout_seconds: int) -> None:
    if prediction_path.exists() or metadata_path.exists():
        raise ValueError(f"partial or unverified prediction exists; refusing overwrite: {prediction_path}")
    command = prediction_command(input_path, prediction_path, model, spec, arm, cpu_threads)
    env = os.environ.copy()
    env.update({
        "HF_HOME": "/opt/models/.cache/huggingface",
        "OMP_NUM_THREADS": str(cpu_threads),
        "MKL_NUM_THREADS": str(cpu_threads),
        "OPENBLAS_NUM_THREADS": str(cpu_threads),
        "NUMEXPR_NUM_THREADS": str(cpu_threads),
        "TOKENIZERS_PARALLELISM": "false",
        "PYTHONUNBUFFERED": "1",
    })
    log_path = _next_job_log(work_dir, run_id, spec, arm)
    print(f"[{run_id}] starting {spec.context_tokens}/{spec.task_name}/{arm}; log={log_path}", flush=True)
    with log_path.open("x", encoding="utf-8") as log:
        log.write("command: " + stable_json(command) + "\n")
        log.flush()
        process = subprocess.Popen(
            command, cwd=repo_root(), env=env, stdout=log, stderr=subprocess.STDOUT,
            start_new_session=(os.name == "posix"),
        )
        try:
            return_code = process.wait(timeout=timeout_seconds)
        except subprocess.TimeoutExpired as exc:
            if os.name == "posix":
                os.killpg(process.pid, signal.SIGTERM)
            else:
                process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                if os.name == "posix":
                    os.killpg(process.pid, signal.SIGKILL)
                else:
                    process.kill()
                process.wait()
            raise TimeoutError(f"model job timed out after {timeout_seconds}s; log={log_path}") from exc
    if return_code != 0:
        raise RuntimeError(f"model job exited {return_code}; log={log_path}")


def score_predictions(spec: DatasetSpec, source_rows: list[dict[str, Any]],
                      prediction_rows: list[dict[str, Any]], audit_rows: list[dict[str, Any]],
                      metric_fn: Callable, postprocess: Callable, constants_path: Path,
                      evaluate_path: Path, source_meta: dict[str, Any], input_path: Path,
                      prediction_path: Path, metadata_path: Path, model: Path,
                      arm: str, run_id: str) -> dict[str, Any]:
    normalized: list[str] = []
    refs: list[list[str]] = []
    scored_rows = []
    for source, prediction, audit in zip(source_rows, prediction_rows, audit_rows):
        raw_pred = prediction["pred"]
        scored_pred = postprocess(raw_pred, {"task": spec.task_name})
        row_refs = source["outputs"]
        normalized.append(scored_pred)
        refs.append(row_refs)
        scored_rows.append({
            "row_number": audit["row_number"],
            "source_identity": source_identity(source),
            "prompt_sha256": audit["prompt_sha256"],
            "input_token_length": audit["input_token_length"],
            "prediction": raw_pred,
            "scored_prediction": scored_pred,
            "references": row_refs,
            "official_sample_score_percent": metric_fn([scored_pred], [row_refs]),
            "output_token_ids": audit["output_token_ids"],
            "generated_tokens": audit["generated_tokens"],
            "max_new_tokens": spec.max_new_tokens,
            "hit_max_tokens": audit["hit_max_tokens"],
        })
    return {
        "schema_version": 1,
        "status": "complete",
        "run_id": run_id,
        "context_tokens": spec.context_tokens,
        "task": spec.task_name,
        "metric_task": spec.metric_task,
        "arm": arm,
        "model": str(model),
        "input": {"path": str(input_path), "sha256": sha256_file(input_path), "samples": len(source_rows)},
        "prediction": {"sha256": sha256_file(prediction_path), "metadata_sha256": sha256_file(metadata_path)},
        "metric": {
            "score_percent": metric_fn(normalized, refs),
            "name": spec.metric_task,
            "source": str(constants_path),
            "source_sha256": sha256_file(constants_path),
            "normalization_source": str(evaluate_path) + "::postprocess_pred",
            "normalization_source_sha256": sha256_file(evaluate_path),
        },
        "configuration": source_meta["configuration"],
        "adapter_source": source_meta["source"],
        "hit_max_tokens_count": sum(row["hit_max_tokens"] for row in scored_rows),
        "rows": scored_rows,
    }


def run_identity(plan: dict[str, Any], spec: DatasetSpec, arm: str) -> str:
    return sha256_json({"plan": plan, "dataset": asdict(spec), "arm": arm})


def require_matched_prompts(arms: dict[str, dict[str, Any]], expected_samples: int) -> list[str]:
    baseline = arms["sparse_baseline"]["rows"]
    reference = [row["prompt_sha256"] for row in baseline]
    if len(reference) != expected_samples:
        raise ValueError("sparse baseline row count differs from the frozen input")
    for arm, result in arms.items():
        candidate = [row["prompt_sha256"] for row in result["rows"]]
        if candidate != reference:
            raise ValueError(f"prompt hashes differ across arms for {arm}")
    return reference


def run_arm(spec: DatasetSpec, arm: str, args: argparse.Namespace,
            input_rows: list[dict[str, Any]], input_hash: str, plan: dict[str, Any],
            metric_fn: Callable, postprocess: Callable, constants_path: Path,
            evaluate_path: Path, model: Path) -> dict[str, Any]:
    prediction_path, metadata_path = prediction_paths(args.work_dir, args.run_id, spec, arm)
    public_path = public_arm_path(args.results_dir, args.run_id, spec, arm)
    identity = run_identity(plan, spec, arm)
    if public_path.exists():
        existing = read_json(public_path)
        if (existing.get("run_identity") != identity or existing.get("status") != "complete"
                or existing.get("model") != str(model)
                or existing.get("arm") != arm
                or existing.get("input", {}).get("sha256") != input_hash
                or len(existing.get("rows", [])) != spec.samples):
            raise ValueError(f"existing public result does not match this run; refusing overwrite: {public_path}")
        for source, scored in zip(input_rows, existing["rows"]):
            prompt = source["input"] + source.get("answer_prefix", "")
            prompt_sha = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
            if (scored.get("source_identity") != source_identity(source)
                    or scored.get("prompt_sha256") != prompt_sha
                    or scored.get("references") != source["outputs"]
                    or scored.get("max_new_tokens") != spec.max_new_tokens):
                raise ValueError(f"existing public result row mismatch: {public_path}")
        print(f"[{args.run_id}] reusing compact result {public_path}", flush=True)
        return existing

    if prediction_path.exists() and metadata_path.exists():
        prediction_rows = read_jsonl(prediction_path)
        metadata = read_json(metadata_path)
        audit_rows = validate_adapter_metadata(
            metadata, prediction_rows, input_rows, dataset_path(args.work_dir, spec),
            input_hash, model, spec, arm, args.cpu_threads,
        )
    elif prediction_path.exists() or metadata_path.exists():
        raise ValueError(f"incomplete prediction/metadata pair; refusing overwrite: {prediction_path}")
    else:
        run_prediction(
            dataset_path(args.work_dir, spec), prediction_path, metadata_path, model,
            args.work_dir, args.run_id, spec, arm, args.cpu_threads,
            args.job_timeout_seconds,
        )
        prediction_rows = read_jsonl(prediction_path)
        metadata = read_json(metadata_path)
        audit_rows = validate_adapter_metadata(
            metadata, prediction_rows, input_rows, dataset_path(args.work_dir, spec),
            input_hash, model, spec, arm, args.cpu_threads,
        )

    result = score_predictions(
        spec, input_rows, prediction_rows, audit_rows, metric_fn, postprocess,
        constants_path, evaluate_path, metadata, dataset_path(args.work_dir, spec),
        prediction_path, metadata_path, model, arm, args.run_id,
    )
    result["run_identity"] = identity
    write_json_once(public_path, result)
    print(f"[{args.run_id}] scored {spec.context_tokens}/{spec.task_name}/{arm}: "
          f"{result['metric']['score_percent']:.2f}% ({spec.samples} samples)", flush=True)
    return result


def arms_for(spec: DatasetSpec) -> tuple[str, ...]:
    if spec.context_tokens == 8192:
        return "dense", "sparse_baseline", "m21_static_mask"
    return "sparse_baseline", "m21_static_mask"


def build_summary(plan: dict[str, Any], plan_hash: str,
                  results: dict[tuple[int, str, str], dict[str, Any]], run_id: str) -> dict[str, Any]:
    tasks = []
    for spec in DATASETS:
        arms = {arm: results[(spec.context_tokens, spec.task_name, arm)] for arm in arms_for(spec)}
        require_matched_prompts(arms, spec.samples)
        core_hashes = arms["sparse_baseline"]["adapter_source"]["core_file_sha256"]
        for arm, result in arms.items():
            if result["adapter_source"]["core_file_sha256"] != core_hashes:
                raise ValueError(f"NanoKV core source hashes changed across arms for {spec.context_tokens}/{spec.task_name}")
        baseline = arms["sparse_baseline"]
        m21 = arms["m21_static_mask"]
        token_equal = [
            left["output_token_ids"] == right["output_token_ids"]
            for left, right in zip(baseline["rows"], m21["rows"])
        ]
        text_equal = [
            left["prediction"] == right["prediction"]
            for left, right in zip(baseline["rows"], m21["rows"])
        ]
        tasks.append({
            "context_tokens": spec.context_tokens,
            "task": spec.task_name,
            "metric_task": spec.metric_task,
            "samples": spec.samples,
            "max_new_tokens": spec.max_new_tokens,
            "arms": {
                arm: {
                    "score_percent": result["metric"]["score_percent"],
                    "hit_max_tokens_count": result["hit_max_tokens_count"],
                    "result_path": str(public_arm_path(Path(plan["results_dir"]), run_id, spec, arm)),
                } for arm, result in arms.items()
            },
            "core_source_sha256": core_hashes,
            "sparse_baseline_vs_m21": {
                "token_ids_equal_samples": sum(token_equal),
                "text_equal_samples": sum(text_equal),
                "samples": spec.samples,
                "score_delta_percentage_points": round(
                    m21["metric"]["score_percent"] - baseline["metric"]["score_percent"], 4),
            },
        })
    return {
        "schema_version": 1,
        "status": "complete",
        "run_id": run_id,
        "run_identity": plan_hash,
        "claim_scope": "bounded matched quality regression screen; not a full RULER benchmark",
        "ruler_commit": RULER_COMMIT,
        "model": plan["model"],
        "seed": SEED,
        "arms": list(ARM_SPECS),
        "tasks": tasks,
    }


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    root = resolve_ruler_root(args.ruler_root)
    model = args.model.resolve()
    if not model.is_dir():
        raise FileNotFoundError(f"Qwen3-4B model/tokenizer directory not found: {model}")
    work_dir = args.work_dir.resolve()
    results_dir = args.results_dir.resolve()
    args.work_dir = work_dir
    args.results_dir = results_dir
    source_hashes = ruler_source_manifest(root)

    input_rows: dict[tuple[int, str], list[dict[str, Any]]] = {}
    dataset_hashes: dict[str, dict[str, Any]] = {}
    for data_spec in DATASETS:
        generated = prepare_dataset(
            root, model, work_dir, args.nltk_data, args.run_id,
            data_spec, args.skip_prepare,
        )
        path = dataset_path(work_dir, data_spec)
        rows = validate_dataset(path, data_spec)
        input_rows[(data_spec.context_tokens, data_spec.task_name)] = rows
        dataset_hashes[f"{data_spec.context_tokens}/{data_spec.task_name}"] = {
            "path": str(path),
            "sha256": sha256_file(path),
            "samples": len(rows),
            "context_tokens": data_spec.context_tokens,
            "task": data_spec.task_name,
            "metric_task": data_spec.metric_task,
            "max_new_tokens": data_spec.max_new_tokens,
        }
    input_manifest = freeze_inputs(
        work_dir, results_dir, args.run_id, root, model, source_hashes, dataset_hashes,
    )

    plan = {
        "schema_version": 1,
        "run_id": args.run_id,
        "runner_sha256": sha256_file(Path(__file__).resolve()),
        "model": str(model),
        "results_dir": str(results_dir / args.run_id),
        "work_dir": str(work_dir),
        "input_manifest_sha256": sha256_json(input_manifest),
        "ruler_commit": RULER_COMMIT,
        "ruler_source_sha256": source_hashes,
        "seed": SEED,
        "tokenizer_type": "hf",
        "rope_mode": "yarn",
        "generation": {"temperature": 0.0, "ignore_eos": False},
        "sparse": {
            "top_k": 32, "prefill_top_k": 32, "decode_top_k": 32,
            "dynamic_top_k": False, "index_select": True,
            "selector_cuda_graph": False, "decode_kv_pipeline": False,
        },
        "cpu_threads": args.cpu_threads,
        "job_timeout_seconds": args.job_timeout_seconds,
        "datasets": dataset_hashes,
        "arms": {arm: cfg for arm, cfg in ARM_SPECS.items()},
    }
    plan_hash = sha256_json(plan)
    result_dir = results_dir / args.run_id
    write_json_once(result_dir / "plan.json", {**plan, "run_identity": plan_hash})
    if args.prepare_only:
        print(json.dumps({"status": "inputs_ready", "run_id": args.run_id,
                          "input_manifest": str(work_dir / "input_manifests" / f"{args.run_id}.json"),
                          "datasets": dataset_hashes}, ensure_ascii=False, indent=2))
        return 0

    constants_path = root / "scripts/eval/synthetic/constants.py"
    evaluate_path = root / "scripts/eval/evaluate.py"
    metric_cache: dict[str, Callable] = {}
    postprocess = load_official_postprocess(evaluate_path)
    completed_results: dict[tuple[int, str, str], dict[str, Any]] = {}
    for data_spec in DATASETS:
        key = (data_spec.context_tokens, data_spec.task_name)
        metric_fn = metric_cache.setdefault(
            data_spec.metric_task, load_official_metric(constants_path, data_spec.metric_task))
        input_path = dataset_path(work_dir, data_spec)
        input_hash = dataset_hashes[f"{data_spec.context_tokens}/{data_spec.task_name}"]["sha256"]
        rows = input_rows[key]
        for arm in arms_for(data_spec):
            completed_results[(data_spec.context_tokens, data_spec.task_name, arm)] = run_arm(
                data_spec, arm, args, rows, input_hash, plan, metric_fn, postprocess,
                constants_path, evaluate_path, model,
            )

    summary = build_summary(plan, plan_hash, completed_results, args.run_id)
    summary_path = result_dir / "summary.json"
    if write_json_once(summary_path, summary):
        print(f"[{args.run_id}] wrote final summary: {summary_path}", flush=True)
    else:
        print(f"[{args.run_id}] final summary already exists and matches: {summary_path}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
