def validate_adapter_metadata(metadata: dict[str, Any], prediction_rows: list[dict[str, Any]],
                              input_rows: list[dict[str, Any]], input_path: Path,
                              input_sha: str, model: Path, spec: DatasetSpec, arm: str,
                              cpu_threads: int) -> list[dict[str, Any]]:
    if metadata.get("status") != "complete":
        raise ValueError("adapter metadata does not mark the run complete")
    if metadata.get("input", {}).get("sha256") != input_sha:
        raise ValueError("adapter input hash differs from the frozen RULER input")
    if metadata.get("input", {}).get("rows_processed") != spec.samples:
        raise ValueError("adapter processed row count differs from the frozen input")
    if Path(metadata.get("input", {}).get("path", "")).resolve() != input_path.resolve():
        raise ValueError("adapter metadata points at a different input file")
    if Path(metadata.get("model", "")).resolve() != model.resolve():
        raise ValueError("adapter used a different model path")
    configuration = metadata.get("configuration", {})
    if configuration.get("cpu_threads") != cpu_threads:
        raise ValueError("adapter CPU thread count differs from the matched plan")
    sampling = configuration.get("sampling", {})
    if (sampling.get("max_tokens") != spec.max_new_tokens
            or sampling.get("temperature") != 0.0
            or sampling.get("ignore_eos") is not False):
        raise ValueError("adapter generation settings differ from the RULER task budget")
    llm_config = configuration.get("llm", {})
    if llm_config.get("enforce_eager") is not True or llm_config.get("tensor_parallel_size") != 1:
        raise ValueError("adapter runtime is not the expected eager TP=1 configuration")
    if llm_config.get("rope_scaling_override") != expected_llm_config(arm)["rope_scaling_override"]:
        raise ValueError("adapter did not use the matched YaRN setting")
    if arm == "dense":
        if llm_config.get("enable_sparse_attention") or "sparse_selector_static_mask" in llm_config:
            raise ValueError("dense adapter config unexpectedly enables sparse options")
    else:
        fixed = expected_llm_config(arm)
        for key in (
            "enable_sparse_attention", "use_m12_runtime", "sparse_selector",
            "sparse_retrieval_block_size", "sparse_num_representatives",
            "sparse_recent_tokens", "sparse_first_tokens", "sparse_top_k",
            "sparse_prefill_top_k", "sparse_decode_top_k", "sparse_dynamic_top_k",
            "sparse_prefill_chunk_size", "sparse_prefill_query_segments",
            "sparse_prefill_attention_backend", "sparse_gather_index_select",
            "sparse_selector_cuda_graph", "sparse_decode_kv_pipeline",
            "sparse_selector_static_mask",
        ):
            # These two knobs are Config dataclass defaults and are omitted from
            # adapter metadata until explicitly passed through the M16 adapter.
            default_off = key in ("sparse_selector_cuda_graph", "sparse_decode_kv_pipeline")
            actual = llm_config.get(key, False if default_off else None)
            if actual != fixed[key]:
                raise ValueError(f"adapter configuration mismatch for {key}: {llm_config.get(key)!r}")
    if len(prediction_rows) != spec.samples:
        raise ValueError("prediction row count differs from the frozen input")
    audit_rows = metadata.get("rows")
    if not isinstance(audit_rows, list) or len(audit_rows) != spec.samples:
        raise ValueError("adapter per-row metadata is missing or incomplete")

    for i, (source, prediction, audit) in enumerate(zip(input_rows, prediction_rows, audit_rows), start=1):
        if {key: value for key, value in prediction.items() if key != "pred"} != source:
            raise ValueError(f"prediction row {i} does not match the frozen source row")
        if not isinstance(prediction.get("pred"), str):
            raise ValueError(f"prediction row {i} has no string pred")
        if audit.get("row_number") != i or audit.get("input_index") != source.get("index"):
            raise ValueError(f"adapter row identity mismatch at sample {i}")
        if audit.get("source_identity") != source_identity(source):
            raise ValueError(f"adapter source identity mismatch at sample {i}")
        prompt = source["input"] + source.get("answer_prefix", "")
        prompt_sha = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
        if audit.get("prompt_sha256") != prompt_sha:
            raise ValueError(f"adapter prompt hash mismatch at sample {i}")
        token_ids = audit.get("output_token_ids")
        if not isinstance(token_ids, list) or not all(isinstance(token_id, int) for token_id in token_ids):
            raise ValueError(f"adapter token IDs are malformed at sample {i}")
        generated = audit.get("generated_tokens")
        if generated != len(token_ids) or audit.get("hit_max_tokens") != (generated == spec.max_new_tokens):
            raise ValueError(f"adapter token count/cap marker mismatch at sample {i}")
        if not isinstance(audit.get("input_token_length"), int) or audit["input_token_length"] <= 0:
            raise ValueError(f"adapter input token length is invalid at sample {i}")
    return audit_rows


def prediction_command(input_path: Path, output_path: Path, model: Path,
                       spec: DatasetSpec, arm: str, cpu_threads: int) -> list[str]:
    command = [
        sys.executable, "-u", str(repo_root() / "benchmarks/benchmark_m16_ruler.py"),
        "--input", str(input_path), "--output", str(output_path),
        "--limit", str(spec.samples), "--max-tokens", str(spec.max_new_tokens),
        "--model", str(model), "--rope-mode", "yarn", "--top-k", "32",
        "--prefill-top-k", "32", "--cpu-threads", str(cpu_threads),
    ]
    if arm == "dense":
        command.append("--dense")
    elif arm == "m21_static_mask":
        command.append("--selector-static-mask")
    return command


